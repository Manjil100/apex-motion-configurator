/**
 * Writes the seed migration from the app's own data files, so the database and
 * the code start from exactly the same catalogue.
 *
 *   npx tsx tools/db/generate-seed.ts > supabase/migrations/<timestamp>_seed.sql
 */
import { vehicles } from "../../lib/vehicles/data";
import { categories } from "../../lib/customisation/options";

const q = (v: string | number | boolean | null | undefined) =>
  v === null || v === undefined ? "null" : typeof v === "string" ? `'${v.replace(/'/g, "''")}'` : String(v);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const lines: string[] = ["-- Generated by tools/db/generate-seed.ts. Do not edit by hand.", ""];

lines.push(
  "insert into public.vehicles (slug, manufacturer, model, variant, generation, model_year, model_year_status, body_style, drivetrain, layout, engine, facts_status, summary, specs, sort_order) values",
  vehicles
    .map(
      (v, i) =>
        `  (${[v.slug, v.manufacturer, v.model, v.variant, v.generation].map(q).join(", ")}, ${v.modelYear.value}, ${q(v.modelYear.status)}, ${q(v.bodyStyle)}, ${q(v.drivetrain.value)}, ${q(v.layout.value)}, ${q(v.engine.value)}, ${q(v.engine.status)}, ${q(v.summary)}, ${j(v.specs)}, ${i})`,
    )
    .join(",\n") + "\non conflict (slug) do nothing;",
  "",
  "insert into public.vehicle_assets (vehicle_slug, status, model_url, licence, slots, visibility, cameras, lighting) values",
  vehicles
    .map(
      (v) =>
        `  (${q(v.slug)}, ${q(v.asset.status)}, ${q(v.asset.modelUrl)}, ${v.asset.licence ? j(v.asset.licence) : "null"}, ${j(v.asset.slots)}, ${j(v.asset.visibility ?? {})}, ${j(v.asset.cameras)}, ${j(v.asset.lighting)})`,
    )
    .join(",\n") + ";",
  "",
  "insert into public.customisation_categories (id, name, group_name, slot, multi, sort_order) values",
  categories.map((c, i) => `  (${[c.id, c.name, c.group, c.slot].map(q).join(", ")}, ${!!c.multi}, ${i})`).join(",\n") +
    "\non conflict (id) do nothing;",
  "",
  "insert into public.customisation_options (category_id, id, name, price_nzd, price_status, swatch, finish, note, sort_order) values",
  categories
    .flatMap((c) =>
      c.options.map(
        (o, i) =>
          `  (${[c.id, o.id, o.name].map(q).join(", ")}, ${o.price}, 'illustrative', ${q(o.swatch)}, ${q(o.finish)}, ${q(o.note)}, ${i})`,
      ),
    )
    .join(",\n") + "\non conflict (category_id, id) do nothing;",
  "",
);
process.stdout.write(lines.join("\n"));
